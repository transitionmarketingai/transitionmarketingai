// Performance Calculations
export const calculatePerformanceMetrics = (campaign: Campaign): CampaignMetrics => {
  const metrics = campaign.metrics;
  
  // Calculate derived metrics
  const ctr = metrics.impressions && metrics.clicks ? (metrics.clicks / metrics.impressions) * 100 : 0;
  const cpc = metrics.clicks && metrics.cost ? metrics.cost / metrics.clicks : 0;
  const roas = metrics.cost && metrics.revenue ? metrics.revenue / metrics.cost : 0;
  const conversionRate = metrics.clicks && metrics.conversions ? (metrics.conversions / metrics.clicks) * 100 : 0;
  
  return {
    ...metrics,
    ctr: ctr || metrics.ctr,
    cpc: cpc || metrics.cpc,
    roas: roas || metrics.roas,
    conversionRate
  };
};

